import {test} from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {atomicJSON,fileRef,readJSON} from './production-io.mjs';
import {newProduction,persist,readProduction,beginIteration} from './production.mjs';
import {runLocal,resumeLocal} from './run-local.mjs';
import {startWork} from './work.mjs';
import {repairRouting,validateStrategyReview} from './iteration-routing.mjs';
function fixture(t){
  const base=fs.mkdtempSync(path.join(os.tmpdir(),'tripo-automation-'));
  t.after(()=>{assert.equal(path.dirname(base),path.resolve(os.tmpdir()));assert.ok(path.basename(base).startsWith('tripo-automation-'));fs.rmSync(base,{recursive:true,force:true});});
  const put=(name,value)=>{atomicJSON(path.join(base,name),value);return fileRef(base,name);};
  fs.writeFileSync(path.join(base,'source.blend'),'synthetic source');
  fs.writeFileSync(path.join(base,'script.py'),"bpy.context.scene['test_marker'] = 1\n");
  const spec={schema_version:2,status:'active',suite_id:'fixture',basis:'test',motion_required:false,gates:{base_model:['shape'],polish:['shape'],final:['shape']},criteria:{shape:{kind:'visual',description:'Shape'}}};
  const job=newProduction('test',put('spec.json',spec));job.evidence_policy_required=false;job.local_revisions.max_started=8;job.artifacts.candidate=fileRef(base,'source.blend');persist(base,job,{type:'fixture'});
  const plan={operation:'diagnostic',defect_id:'shape',strategy_id:'first',hypothesis:'Collect isolated fixture',authorization_evidence:'test only',success_checks:['shape'],protected_checks:['shape'],output_path:'output.blend',execution:{script:'script.py'}};
  return {base,put,job,plan};
}
test('runner preflight failure consumes no iteration, and resume never launches an orphan dispatch',t=>{
  const {base,job,plan}=fixture(t);
  assert.throws(()=>runLocal(base,plan,{blender:path.join(base,'missing')}),/preflight/);
  assert.equal(readProduction(base).local_revisions.records.length,0);
  const dispatch=startWork(base,plan);
  const current=readProduction(base);delete current.local_revisions.records[0].execution;persist(base,current,{type:'fixture_crash'});
  assert.equal(resumeLocal(base).action,'reconcile_local');
  assert.equal(readProduction(base).local_revisions.records[0].execution.state,'execution_unknown');
  assert.equal(fs.existsSync(dispatch.request+'.started'),false);
  assert.throws(()=>runLocal(base,plan,{blender:'unused'}),/Existing iteration/);
});
test('changing strategy labels cannot bypass repeated-defect diagnosis, stale evidence or same script',t=>{
  const {base,job,plan,put}=fixture(t);
  const priorPlan={...plan,operation:'geometry_repair',execution:{script:fileRef(base,'script.py')}};
  job.local_revisions.records=['a','b'].map((id,i)=>({id,operation:'geometry_repair',defect_id:'shape',strategy_id:'old'+i,status:'completed',outcome:'no_improvement',plan:put(id+'.json',{...priorPlan,strategy_id:'old'+i})}));
  const next={...priorPlan,job_id:job.job_id,source_sha256:job.artifacts.candidate.sha256,quality_spec_sha256:job.quality_spec.sha256,strategy_id:'new',hypothesis:'Changed geometry cause'};
  assert.equal(repairRouting(job)[0].attempts.length,2);
  assert.throws(()=>beginIteration(base,job,put('blocked.json',next)),/strategy_review/);
  const review={...next,previous_attempts:['a','b'],root_cause:'Fixture diagnosis',changed_approach:'Alternative local geometry algorithm',expected_improvement:'Improve shape while preserving material',evidence:[fileRef(base,'source.blend')]};
  next.strategy_review=put('review.json',review);
  assert.throws(()=>validateStrategyReview(base,job,next),/same script/);
  fs.writeFileSync(path.join(base,'different.py'),'# distinct fixture algorithm');next.execution={script:fileRef(base,'different.py')};
  assert.doesNotThrow(()=>validateStrategyReview(base,job,next));
  next.strategy_review=put('stale.json',{...review,source_sha256:'0'.repeat(64)});
  assert.throws(()=>validateStrategyReview(base,job,next),/identity/);
  assert.doesNotThrow(()=>validateStrategyReview(base,job,{...next,operation:'diagnostic'}));
  job.local_revisions.records.push({id:'c',operation:'geometry_repair',defect_id:'shape',status:'completed',outcome:'improved'});
  assert.deepEqual(repairRouting(job),[]);
});
test('real one-shot runner collects receipts/inventory, resumes quality without replay, closes failures and preserves unknown timeout',{skip:!process.env.BLENDER_TEST_EXE},t=>{
  const {base,job,plan,put}=fixture(t),blender=process.env.BLENDER_TEST_EXE;
  const create=path.join(base,'create.py');fs.writeFileSync(create,"import bpy,sys\nbpy.ops.wm.save_as_mainfile(filepath=sys.argv[-1])\n");
  const generated=spawnSync(blender,['--background','--factory-startup','--python-exit-code','1','--python',create,'--',path.join(base,'source.blend')],{encoding:'utf8',timeout:45000,windowsHide:true});
  assert.equal(generated.status,0,generated.stderr);job.artifacts.candidate=fileRef(base,'source.blend');persist(base,job,{type:'real_fixture'});
  const source=job.artifacts.candidate;
  const first=runLocal(base,plan,{blender});assert.equal(first.action,'awaiting_quality_result');
  const technical=readJSON(path.join(base,first.technical_report));assert.equal(technical.quality,'not_evaluated');assert.ok(technical.inventory.objects.length);
  const receipt=technical.receipt;const receiptBefore=fileRef(base,receipt.path);
  put('incomplete-result.json',{status:'completed',summary:'Missing diagnostic evidence conclusion'});
  assert.throws(()=>resumeLocal(base,'incomplete-result.json'),/Diagnostic conclusion/);
  assert.deepEqual(fileRef(base,receipt.path),receiptBefore);
  put('result.json',{status:'completed',diagnostic_conclusion:'inconclusive',summary:'Fixture execution verified; no aesthetic conclusion'});
  assert.equal(resumeLocal(base,'result.json').action,'finished');
  assert.deepEqual(fileRef(base,receipt.path),receiptBefore);assert.deepEqual(fileRef(base,source.path),source);
  assert.equal(resumeLocal(base).action,'nothing_to_resume');
  fs.writeFileSync(path.join(base,'failure.py'),"raise RuntimeError('intentional test failure')\n");
  const failure=runLocal(base,{...plan,output_path:'failed.blend',execution:{script:'failure.py'}},{blender});
  assert.equal(failure.action,'execution_failed');assert.equal(failure.result.status,'failed');
  fs.writeFileSync(path.join(base,'slow.py'),'import time\ntime.sleep(30)\n');
  const timeout=runLocal(base,{...plan,output_path:'slow.blend',execution:{script:'slow.py'}},{blender,timeoutMs:500});
  assert.equal(timeout.action,'reconcile_local');
  assert.equal(resumeLocal(base).action,'reconcile_local');
  assert.equal(readProduction(base).local_revisions.records.length,3);
  assert.deepEqual(fileRef(base,source.path),source);
});
